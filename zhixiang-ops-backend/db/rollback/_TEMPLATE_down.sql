-- 迁移回滚脚本模板（E4）
--
-- 用法：新增一个迁移 db/migrations/NNN_xxx.sql 时，同步在本目录提供
--       NNN_xxx_down.sql，内容为该迁移的逆向 SQL（DROP / ALTER 反向）。
--       db/migrate.ts --rollback --steps N 会按逆序执行最近 N 个迁移的 down 脚本。
--
-- 编写约定：
--   1. 顺序：先删依赖方（索引/子表/补列），再删被依赖方（表/主列），避免遗留孤立对象。
--   2. 破坏性 DDL 前建议加注释说明影响（如：会丢哪些数据），便于回滚前人工确认。
--   3. 回滚脚本是「撤销该迁移」，与迁移文件一一对应；不要写幂等逻辑，缺对象时报错中止
--      （db/migrate.ts 在全部 down 脚本齐全后才开始执行，失败即停，保持数据库为执行前状态）。
--
-- 示例（反向删除一个表）：
-- DROP TABLE IF EXISTS `ops_xxx`;
